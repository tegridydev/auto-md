MARKDOWN_SCHEMA = "automd.markdown.v1"
RAG_SCHEMA = "automd.rag.v1"
_TOKEN = re.compile(r"\w+|[^\w\s]")
_HEADING = re.compile(r"^(#{1,6})[ \t]+(.+)$")
_FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")


def build_artifacts(
    output_dir: Path,
    *,
    requested_name: str,
    documents: list[Document],
    skipped: list[SkipRecord],
    warnings: list[str],
    sources: list[SourceSpec],
    options: ProcessingOptions,
) -> list[Artifact]:
    output_dir.mkdir(parents=True, exist_ok=True)
    base = safe_filename(requested_name or (sources[0].label if sources else "automd-output"))
    base = re.sub(r"\.(md|zip)$", "", base, flags=re.IGNORECASE) or "automd-output"
    markdown_path = output_dir / f"{base}.md"
    with markdown_path.open("x", encoding="utf-8", newline="\n") as stream:
        stream.writelines(_markdown_lines(base, documents, sources, options))
    if options.output_mode == OutputMode.MARKDOWN:
        return [_artifact(markdown_path, "text/markdown")]

    chunks_path = output_dir / "chunks.jsonl"
    chunk_count = chunk_bytes = 0
    with chunks_path.open("xb") as stream:
        for chunk_count, chunk in enumerate(_iter_chunks(documents, options), start=1):
            if chunk_count > LIMITS.max_chunk_count:
                raise SecurityError("RAG chunk limit exceeded. Use larger chunks or fewer sources.")
            line = json.dumps(chunk, ensure_ascii=False, separators=(",", ":")).encode() + b"\n"
            chunk_bytes += len(line)
            if chunk_bytes > LIMITS.max_chunk_bytes:
                raise SecurityError("RAG bundle text limit exceeded. Try fewer sources.")
            stream.write(line)
    manifest = build_manifest(documents, skipped, warnings, sources, options, chunk_count)
    manifest_path = output_dir / "manifest.json"
    with manifest_path.open("x", encoding="utf-8", newline="\n") as stream:
        json.dump(manifest, stream, ensure_ascii=False, indent=2)
        stream.write("\n")
    zip_path = output_dir / f"{base}-rag.zip"
    with zipfile.ZipFile(
        zip_path, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6
    ) as archive:
        archive.write(markdown_path, arcname=markdown_path.name)
        archive.write(chunks_path, arcname=chunks_path.name)
        archive.write(manifest_path, arcname=manifest_path.name)
    for intermediate in (markdown_path, chunks_path, manifest_path):
        intermediate.unlink()
    return [_artifact(zip_path, "application/zip")]


def render_markdown(
    title: str,
    documents: list[Document],
    sources: list[SourceSpec],
    options: ProcessingOptions,
) -> str:
    return "".join(_markdown_lines(title, documents, sources, options))


def _markdown_lines(
    title: str,
    documents: list[Document],
    sources: list[SourceSpec],
    options: ProcessingOptions,
) -> Iterable[str]:
    generated = datetime.now(UTC).isoformat()
    metadata = {
        "schema": MARKDOWN_SCHEMA,
        "generated_at": generated,
        "document_count": len(documents),
        "sources": [
            {"id": source.id, "kind": source.kind, "label": source.label} for source in sources
        ],
    }
    metadata_json = json.dumps(metadata, ensure_ascii=False, separators=(",", ":"))
    metadata_json = metadata_json.replace("--", r"\u002d\u002d")
    yield f"<!-- automd: {metadata_json} -->\n\n# {title}\n\n"
    yield f"> Generated by Auto-MD {__version__} · {generated} · {len(documents)} documents\n"
    anchors = [_anchor(document) for document in documents]
    if options.include_toc and documents:
        yield "\n## Contents\n\n"
        for document, anchor in zip(documents, anchors, strict=True):
            yield f"- [{_inline_code(document.path)}](#{anchor})\n"
    for document, anchor in zip(documents, anchors, strict=True):
        yield f'\n---\n\n<a id="{anchor}"></a>\n\n'
        yield f"## {_inline_code(document.path)}\n\n{_provenance(document)}\n\n"
        yield _document_body(document).rstrip() + "\n"


def build_chunks(documents: list[Document], options: ProcessingOptions) -> list[dict[str, Any]]:
    return list(_iter_chunks(documents, options))


def _iter_chunks(
    documents: list[Document],
    options: ProcessingOptions,
) -> Iterable[dict[str, Any]]:
    for document in documents:
        is_markdown = document.content_kind == "markdown"
        body = _document_body(document) if is_markdown else document.content
        segments = _segments(body, is_markdown)
        grouped = _group_segments(
            segments, options.chunk_target, options.chunk_overlap, preserve_indent=not is_markdown
        )
        heading_path: list[str] = []
        for index, text in enumerate(grouped):
            if is_markdown:
                for level, heading in _headings(text):
                    heading_path = heading_path[: level - 1] + [heading[:512]]
            else:
                fence = markdown_fence(text)
                text = f"{fence}{document.language or 'text'}\n{text}\n{fence}"
            digest_input = "\0".join(
                [document.source_id, document.path, "/".join(heading_path), str(index), text]
            ).encode("utf-8")
            chunk_id = hashlib.sha256(digest_input).hexdigest()[:24]
            yield {
                "schema": RAG_SCHEMA,
                "id": chunk_id,
                "text": text.strip(),
                "title": document.title,
                "source": {
                    "id": document.source_id,
                    "label": document.source_label,
                    "path": document.path,
                    "url": _public_provenance(document.source_url),
                    "sha256": document.sha256,
                },
                "heading_path": heading_path.copy(),
                "language": document.language,
                "chunk_index": index,
                "token_estimate": estimate_tokens(text),
                "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
            }


def build_manifest(
    documents: list[Document],
    skipped: list[SkipRecord],
    warnings: list[str],
    sources: list[SourceSpec],
    options: ProcessingOptions,
    chunk_count: int,
) -> dict[str, Any]:
    return {
        "schema": RAG_SCHEMA,
        "generated_at": datetime.now(UTC).isoformat(),
        "settings": asdict(options),
        "sources": [
            {**asdict(source), "url": _public_provenance(source.url)} for source in sources
        ],
        "documents": [
            {
                "source_id": document.source_id,
                "path": document.path,
                "title": document.title,
                "media_type": document.media_type,
                "language": document.language,
                "url": _public_provenance(document.source_url),
                "sha256": document.sha256,
                "warnings": document.warnings,
            }
            for document in documents
        ],
        "skipped": [asdict(record) for record in skipped],
        "warnings": warnings,
        "counts": {
            "sources": len(sources),
            "documents": len(documents),
            "chunks": chunk_count,
            "skipped": len(skipped),
            "warnings": len(warnings),
        },
    }


def estimate_tokens(text: str) -> int:
    return max(1, math.ceil(sum(1 for _ in _TOKEN.finditer(text)) * 1.15)) if text else 0


def _document_body(document: Document) -> str:
    if document.content_kind == "markdown":
        return _shift_headings(document.content, 2)
    fence = markdown_fence(document.content)
    language = document.language or "text"
    content = document.content.rstrip("\r\n")
    return f"{fence}{language}\n{content}\n{fence}"


def _lines_with_fences(text: str) -> Iterable[tuple[str, bool]]:
    fence = ""
    for line in io.StringIO(text):
        line = line.rstrip("\r\n")
        marker = _FENCE.match(line)
        if marker:
            sequence = marker[1]
            if not fence:
                fence = sequence
                yield line, True
                continue
            if sequence[0] == fence[0] and len(sequence) >= len(fence) and not marker[2].strip():
                fence = ""
                yield line, True
                continue
        yield line, bool(fence)


def _headings(text: str) -> Iterable[tuple[int, str]]:
    for line, fenced in _lines_with_fences(text):
        if not fenced and (match := _HEADING.match(line)):
            yield len(match[1]), match[2].strip()


def _shift_headings(text: str, offset: int) -> str:
    return "\n".join(
        f"{'#' * min(6, len(match[1]) + offset)} {match[2]}"
        if not fenced and (match := _HEADING.match(line))
        else line
        for line, fenced in _lines_with_fences(text)
    )


def _public_provenance(url: str | None) -> str | None:
    if not url:
        return None
    try:
        parsed = urlsplit(url)
        if parsed.scheme in {"http", "https"} and parsed.hostname and parsed.username is None:
            return parsed._replace(query="", fragment="").geturl()
    except ValueError:
        pass
    return None


def _provenance(document: Document) -> str:
    label = re.sub(r"([\\`*_{}\[\]()#.!|])", r"\\\1", html.escape(document.source_label))
    values = [
        f"Source: **{label}**",
        f"Type: `{document.media_type}`",
        f"SHA-256: `{document.sha256}`",
    ]
    if url := _public_provenance(document.source_url):
        values.insert(1, f"URL: {_inline_code(url)}")
    return "> " + " · ".join(values)


def _anchor(document: Document) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", document.path.casefold()).strip("-")[:60] or "document"
    suffix = hashlib.sha256(f"{document.source_id}\0{document.path}".encode()).hexdigest()[:8]
    return f"{slug}-{suffix}"


def _inline_code(value: str) -> str:
    longest = max((len(match[0]) for match in re.finditer(r"`+", value)), default=0)
    fence = "`" * (longest + 1)
    return f"{fence} {value} {fence}" if longest else f"`{value}`"


def _segments(text: str, markdown: bool) -> Iterable[str]:
    if not markdown:
        yield text
        return
    current: list[str] = []
    for line, fenced in _lines_with_fences(text):
        if not fenced and (not line.strip() or _HEADING.match(line)):
            if current:
                yield "\n".join(current).strip()
                current = []
            if line.strip():
                yield line.strip()
        else:
            current.append(line)
    if current and (segment := "\n".join(current).strip()):
        yield segment


def _group_segments(
    segments: Iterable[str], target: int, overlap: int, *, preserve_indent: bool = False
) -> Iterable[str]:
    char_limit = min(32_000, target * 8)
    current: list[tuple[str, int]] = []
    tokens = chars = 0
    for segment in segments:
        for piece in _split_segment(segment, target, char_limit, preserve_indent=preserve_indent):
            cost = estimate_tokens(piece)
            if current and (tokens + cost > target or chars + len(piece) + 2 > char_limit):
                yield "\n\n".join(text for text, _ in current)
                retained: list[tuple[str, int]] = []
                tokens = chars = 0
                for text, previous_cost in reversed(current):
                    if tokens + previous_cost > overlap or (
                        chars + len(text) + len(piece) + 4 > char_limit
                        or tokens + previous_cost + cost > target
                    ):
                        break
                    retained.append((text, previous_cost))
                    tokens += previous_cost
                    chars += len(text) + 2
                current = list(reversed(retained))
            current.append((piece, cost))
            tokens += cost
            chars += len(piece) + 2
    if current:
        yield "\n\n".join(text for text, _ in current)


def _split_segment(
    text: str, target: int, char_limit: int, *, preserve_indent: bool
) -> Iterable[str]:
    # Search only within one bounded window. A giant unbroken identifier still splits.
    start = 0
    token_limit = max(1, int(target / 1.15))
    while start < len(text):
        end = min(start + char_limit, len(text))
        for index, token in enumerate(_TOKEN.finditer(text, start, end)):
            if index == token_limit:
                end = token.start()
                break
        if end < len(text):
            newline = text.rfind("\n", start + (end - start) // 2, end)
            if newline > start:
                end = newline + 1
        piece = text[start:end]
        if not preserve_indent:
            piece = piece.strip()
        if piece:
            yield piece
        start = end


def _artifact(path: Path, media_type: str) -> Artifact:
    with path.open("rb") as stream:
        digest = hashlib.file_digest(stream, "sha256").hexdigest()
    return Artifact(
        id=secrets.token_urlsafe(12),
        name=path.name,
        media_type=media_type,
        path=path,
        size=path.stat().st_size,
        sha256=digest,
    )
